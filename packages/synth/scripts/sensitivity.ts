/**
 * Writes docs/evaluation/score-sensitivity.md: how the Social Health Score
 * responds to its weights and parameters, and whether any component
 * dominates. Run: npm run sensitivity
 */
import { DEFAULT_CONFIG, MODEL_VERSION, computeScore, type ModelConfig } from '@sg/score-engine';
import fc from 'fast-check';
import { AS_OF, ARB_AS_OF, arbEventLog } from '../src';
import {
  COMPONENTS,
  NAMED_SCENARIOS,
  ORDERINGS,
  compare,
  contributions,
  pearson,
  scoreAll,
  varianceShares,
  withWeights,
} from '../src/analysis';

const SEED = 42;
const SAMPLES = 500;
const f1 = (x: number) => (Number.isNaN(x) ? 'n/a' : x.toFixed(1));
const f2 = (x: number) => (Number.isNaN(x) ? 'n/a' : x.toFixed(2));
const lines: string[] = [];
const out = (s = '') => lines.push(s);
const row = (cells: (string | number)[]) => out(`| ${cells.join(' | ')} |`);
const head = (cells: string[]) => {
  row(cells);
  row(cells.map(() => '---'));
};

const baseline = scoreAll(DEFAULT_CONFIG, AS_OF);
const W = DEFAULT_CONFIG.componentWeights;

out('# Score sensitivity and ablation analysis');
out();
out(`Generated by \`npm run sensitivity\` (packages/synth/scripts/sensitivity.ts) for score model v${MODEL_VERSION}.`);
out('Deterministic: fixed scenarios and a seeded random sample, so it reproduces exactly.');
out();
out('**Method.** Every comparison is against the baseline model on the named synthetic scenarios. Rank agreement is');
out('Spearman ρ between baseline and variant totals across all scenarios (1 = same ranking). "Orderings broken" lists');
out(`which of the ${ORDERINGS.length} pairwise expectations (decided before the formulas; see orderings.test.ts) no longer hold.`);
out();

// A. Scenario profiles
out('## A. Scenario profiles (baseline)');
out();
out(`Weights: ${COMPONENTS.map((c) => `${c} ${W[c]}`).join(', ')}. Components in [0, 1]; "–" = not applicable (left out, weight redistributed).`);
out();
head(['Scenario', 'Total', ...COMPONENTS]);
for (const [name, r] of Object.entries(baseline)) {
  row([name, f1(r.total), ...COMPONENTS.map((c) => (r.components[c] === null ? '–' : f2(r.components[c]!)))]);
}
out();

// B. Ablation
out('## B. Ablation: remove one component');
out();
out('The component\'s weight is set to 0 and the rest renormalised.');
out();
head(['Removed', 'Rank agreement ρ', 'Max |Δ total|', 'Orderings broken']);
for (const c of COMPONENTS) {
  const r = compare(baseline, scoreAll(withWeights({ [c]: 0 }), AS_OF));
  row([c, f2(r.spearman), f1(r.maxAbsDelta), r.violated.join(', ') || 'none']);
}
out();

// C. Weight perturbation
out('## C. Weight perturbation: one weight at a time');
out();
head(['Component', 'Weight ×0.5: ρ', 'max |Δ|', 'broken', 'Weight ×1.5: ρ', 'max |Δ|', 'broken']);
for (const c of COMPONENTS) {
  const lo = compare(baseline, scoreAll(withWeights({ [c]: W[c] * 0.5 }), AS_OF));
  const hi = compare(baseline, scoreAll(withWeights({ [c]: W[c] * 1.5 }), AS_OF));
  row([c, f2(lo.spearman), f1(lo.maxAbsDelta), lo.violated.join(', ') || 'none', f2(hi.spearman), f1(hi.maxAbsDelta), hi.violated.join(', ') || 'none']);
}
out();

// D. Parameter sensitivity
out('## D. Parameter sensitivity');
out();
const variants: [string, ModelConfig][] = [
  ['Saturation k ×0.5 (faster saturation)', { ...DEFAULT_CONFIG, saturation: 0.5 }],
  ['Saturation k ×2 (slower saturation)', { ...DEFAULT_CONFIG, saturation: 2 }],
  ['Frecency half-life 15 days', { ...DEFAULT_CONFIG, frecencyHalfLifeDays: 15 }],
  ['Frecency half-life 60 days', { ...DEFAULT_CONFIG, frecencyHalfLifeDays: 60 }],
  ['Coverage grace ×0.5', { ...DEFAULT_CONFIG, coverageGrace: 0.5 }],
  ['Coverage grace ×2', { ...DEFAULT_CONFIG, coverageGrace: 2 }],
  ['Message weight 0.1', { ...DEFAULT_CONFIG, interactionWeights: { ...DEFAULT_CONFIG.interactionWeights, message: 0.1 } }],
  ['Message weight 0.4', { ...DEFAULT_CONFIG, interactionWeights: { ...DEFAULT_CONFIG.interactionWeights, message: 0.4 } }],
  ['Short calls count 0', { ...DEFAULT_CONFIG, calls: { ...DEFAULT_CONFIG.calls, shortCallWeight: 0 } }],
  ['Short calls count 0.6', { ...DEFAULT_CONFIG, calls: { ...DEFAULT_CONFIG.calls, shortCallWeight: 0.6 } }],
  ['Equal weights (1/6 each)', withWeights(Object.fromEntries(COMPONENTS.map((c) => [c, 1 / 6])))],
];
head(['Variant', 'Rank agreement ρ', 'Max |Δ total|', 'Orderings broken']);
for (const [label, config] of variants) {
  const r = compare(baseline, scoreAll(config, AS_OF));
  row([label, f2(r.spearman), f1(r.maxAbsDelta), r.violated.join(', ') || 'none']);
}
out();

// E. Dominance on random networks
const logs = fc.sample(arbEventLog(), { seed: SEED, numRuns: SAMPLES });
const contribs = logs.map((log) => contributions(computeScore(log, DEFAULT_CONFIG, ARB_AS_OF).components, W));
const results = logs.map((log) => computeScore(log, DEFAULT_CONFIG, ARB_AS_OF));
const shares = varianceShares(contribs);
const totals = results.map((r) => r.total);
const weightSum = COMPONENTS.reduce((a, c) => a + W[c], 0);
out(`## E. Does any component dominate? (${SAMPLES} random networks, seed ${SEED})`);
out();
out('Random event logs from the property-test generator (1–8 people, up to 40 contacts and 20 calls, random');
out('states, ratings, pauses; call log connected in about half). For each component: its nominal weight, the');
out('share of the total\'s variance it accounts for (cov(contributionᶜ, total) / var(total); shares sum to 1), and');
out('the correlation of the component\'s value with the total where it is defined.');
out();
head(['Component', 'Weight', 'Variance share', 'Mean contribution (points)', 'corr(value, total)', 'Defined in']);
for (const c of COMPONENTS) {
  const defined = results.filter((r) => r.components[c] !== null);
  const corr = pearson(
    defined.map((r) => r.components[c]!),
    defined.map((r) => r.total),
  );
  const mean = contribs.reduce((a, x) => a + x[c], 0) / contribs.length;
  row([c, f2(W[c] / weightSum), f2(shares[c]), f1(mean), f2(corr), `${defined.length}/${SAMPLES}`]);
}
out();
const maxShare = Math.max(...COMPONENTS.map((c) => shares[c]));
const dominant = COMPONENTS.filter((c) => shares[c] > 0.5);
out(
  dominant.length
    ? `**Finding:** ${dominant.join(', ')} accounts for more than half of the variance in the total.`
    : `**Finding:** no component accounts for more than half of the variance in the total (largest share ${f2(maxShare)}).`,
);
out();

// Totals distribution
const sorted = [...totals].sort((a, b) => a - b);
const q = (p: number) => sorted[Math.min(sorted.length - 1, Math.floor(p * sorted.length))]!;
out(`Distribution of totals over the sample: min ${f1(sorted[0]!)}, 25th ${f1(q(0.25))}, median ${f1(q(0.5))}, 75th ${f1(q(0.75))}, max ${f1(sorted.at(-1)!)}.`);
out();
out(`Scenarios used: ${Object.keys(NAMED_SCENARIOS).length}. Orderings: ${ORDERINGS.map(([l, h, lo]) => `${l} (${h} > ${lo})`).join('; ')}.`);

console.log(lines.join('\n'));
